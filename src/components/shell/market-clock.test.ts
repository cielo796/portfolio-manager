import { describe, expect, it } from 'vitest';
import { marketClock } from './market-clock';

describe('市場の時計', () => {
  it.each([
    ['2026-10-23T00:00:00Z', '取引中'],
    ['2026-10-23T02:29:59Z', '取引中'],
    ['2026-10-23T02:30:00Z', '時間外'],
    ['2026-10-23T03:30:00Z', '取引中'],
    ['2026-10-23T06:30:00Z', '時間外'],
    ['2026-10-24T01:00:00Z', '時間外'],
  ])('東証の取引時間と昼休み %s', (iso, status) => {
    expect(marketClock(new Date(iso), 'tokyo').status).toBe(status);
  });

  it.each([
    ['2026-10-23T08:00:00Z', '04:00:00', 'プレ'],
    ['2026-10-23T13:30:00Z', '09:30:00', '取引中'],
    ['2026-10-23T20:00:00Z', '16:00:00', 'アフター'],
    ['2026-10-24T00:00:00Z', '20:00:00', '時間外'],
    ['2026-10-24T14:00:00Z', '10:00:00', '時間外'],
    ['2026-12-01T14:30:00Z', '09:30:00', '取引中'],
  ])('NYの夏時間・冬時間とセッション %s', (iso, time, status) => {
    expect(marketClock(new Date(iso), 'ny')).toEqual({ time, status });
  });
});
